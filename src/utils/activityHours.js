/**
 * ข้อความ "ชั่วโมงกิจกรรม" บนหน้าขอบคุณ — แหล่งเดียวของทุก template
 *
 * ทำไมต้องรวมไว้ที่เดียว: ตัวเลขชั่วโมงคือ "คำสัญญา" เรื่องหน่วยกิจกรรมที่คณะเป็นคน
 * กำหนด ไม่ใช่ของตกแต่งของธีม ก่อนหน้านี้ 5 ตระกูล hardcode ว่า "2 ชั่วโมง" ส่วน
 * original กับ receipt พูดถึงชั่วโมงโดยไม่มีเลข — ปีไหนคณะเปลี่ยนเป็น 1 ชั่วโมง
 * เว็บจะบอกนักศึกษาผิดพร้อมกันห้าที่โดยไม่มีใครรู้
 *
 * ค่าเริ่มต้นคือ "ไม่ตั้ง" โดยเจตนา: ถ้าตั้งค่าเริ่มต้นเป็นเลขใดเลขหนึ่ง แล้วสโมฯ ไม่เคย
 * เข้ามาแก้ เว็บก็จะประกาศเลขที่ระบบเดาเอง ซึ่งคือปัญหาเดิมทุกประการ ไม่ตั้ง = พูดแค่
 * "รับชั่วโมงกิจกรรม" ซึ่งจริงเสมอ
 */

/** ตัวเลขชั่วโมงที่ตั้งไว้ หรือ null ถ้าไม่ได้ตั้ง / ตั้งค่าที่ใช้ไม่ได้ */
export function activityHours(gc) {
  const raw = gc?.activityHours;
  if (raw === null || raw === undefined || raw === "") return null;
  const n = Number(raw);
  if (!Number.isFinite(n) || n <= 0) return null;
  // เศษส่วนใช้ได้ (1.5 ชั่วโมง) แต่ตัดหางศูนย์ทิ้งเพื่อไม่ให้ขึ้นว่า "2.0 ชั่วโมง"
  return Math.round(n * 100) / 100;
}

/** "รับชั่วโมงกิจกรรม" หรือ "รับชั่วโมงกิจกรรม 2 ชั่วโมง" */
export function activityHoursPhrase(gc) {
  const n = activityHours(gc);
  return n === null ? "รับชั่วโมงกิจกรรม" : `รับชั่วโมงกิจกรรม ${n} ชั่วโมง`;
}

/**
 * ประโยคเต็มที่อธิบายว่าทำแบบประเมินแล้วได้อะไร — ทุกตระกูลใช้ประโยคเดียวกัน
 * ปรากฏ "ครั้งเดียวต่อหน้า" (ในบรรทัดอธิบายใต้หัวข้อ) หัวข้อกับปุ่มไม่ต้องแบกตัวเลข
 * เพราะพื้นที่ของแต่ละธีมไม่เท่ากัน
 */
export function evaluationPromptText(gc) {
  return `ทำแบบประเมินให้ครบถ้วนเพื่อ${activityHoursPhrase(gc)} และปลดล็อกหน้าผลคะแนน`;
}
